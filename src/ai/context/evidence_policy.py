"""Shared prompt contract for player-visible facts and NPC testimony."""

PUBLIC_EVIDENCE_BOUNDARY = """## 线索披露与证词来源
- 先看当前分支的发现记录与本轮已提交的回执。模组、Skill、守秘人笔记、候选线索和其他角色的私有设定是备查材料。模组里的 tier 标明披露阶段。同一 tier 有线索已公开，也只代表那条线索已公开。
- clue_disclosure.registered_ids 列的是当前分支已经登记的线索。未登记且本轮还未结算的线索，不能通过对白、旁白、选项或修复稿提前交付。完整或部分名称、标题、引文及足以辨认的物证特征均受约束。模组明确指定的公开开场信息按已授权的开场材料呈现。本轮刚合法结算的发现立即可叙述。
- 逐个核对发言者。亲历须有该人物的明确设定、已发生互动或亲自见闻的记录。转述须能指向原讲述者或已有文书，并明确说是转述。关联 NPC、同处一地、玩家已知或别的角色知道，都不能自动证明这个人也知道，更不能证明其亲眼所见。
- 每项具体物证都要有可核对的来源，例如模组明确给该角色的信件、当前分支已查获的记录、已发生的对话或物品交接。registered_sources 里记录的是线索的出处，不证明某个 NPC 亲自经手。证据只能支持记录写明的结论。知道某人买过一件东西，不能推断谁亲眼见过藏处，也不能补造收条、抽屉记录、转述人或拿到物证的经过。
- 玩家问「你看见了吗」「你怎么知道」时，直接说明已知部分、来源类型和未知部分。找不到依据就坦白无法确认，别用模糊的「听人说」填补。裁决模型的 description 或 npc_direction 只是当前行动的叙述建议，不能作为新证词或物证的出处。
- 回顾时仍可引用当前分支中确有来源的公开信息和玩家自己的原话。引用不会补登记线索，也不会把玩家说过的话变成所有 NPC 的亲历。修复或改写时保留有据的内容，纠正草稿中提前泄露或凭空添加的证词。"""
